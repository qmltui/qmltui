function main(terminal) {
    terminal.expectText("btop")
    terminal.expectText("PROCESSES")
    terminal.expectText("NETWORK")
    terminal.expectText("MEMORY")
    terminal.expectText("¹cpu")
    terminal.expectText("preset *")
    terminal.expectRegex("[⠁-⣿]")
    const coreRows = terminal.frameText().split("\n")
    const core9Row = coreRows.find((line) => line.includes("C9 "))
    const core10Row = coreRows.find((line) => line.includes("C10"))
    if (core9Row && core10Row && core9Row.indexOf("%") !== core10Row.indexOf("%"))
        terminal.fail("Single- and double-digit core percentages are not aligned")
    terminal.captureText("initial.txt")
    terminal.press("1")
    terminal.expectNoText("preset *")
    terminal.expectText("PROCESSES")
    terminal.captureText("cpu-hidden.txt")
    terminal.press("1")
    terminal.expectText("preset *")
    terminal.press("2")
    terminal.expectNoText("MEMORY")
    terminal.expectNoText("disks")
    terminal.press("2")
    terminal.expectText("MEMORY")
    terminal.press("3")
    terminal.expectNoText("NETWORK")
    terminal.press("3")
    terminal.expectText("NETWORK")
    terminal.press("4")
    terminal.expectNoText("PROCESSES")
    terminal.expectText("MEMORY")
    terminal.captureText("processes-hidden.txt")
    terminal.press("4")
    terminal.expectText("PROCESSES")
    terminal.press("2")
    terminal.press("3")
    terminal.press("4")
    terminal.expectText("preset *")
    terminal.expectText("LAV:")
    terminal.captureText("cpu-focus.txt")
    const focusedCoreRows = terminal.frameText().split("\n")
    if (focusedCoreRows.some((line) => /[⠁-⣿]/.test(line.slice(1, 61))))
        terminal.fail("Sparse CPU history was stretched across the empty graph area")
    const focusedCore9Row = focusedCoreRows.find((line) => line.includes("C9 "))
    const focusedCore10Row = focusedCoreRows.find((line) => line.includes("C10"))
    if (focusedCore9Row && focusedCore10Row
            && focusedCore9Row.indexOf("%") !== focusedCore10Row.indexOf("%"))
        terminal.fail("Focused CPU core percentages are not aligned")
    terminal.press("2")
    terminal.press("3")
    terminal.press("4")
    terminal.expectText("PROCESSES")
    terminal.press("Space")
    terminal.expectText("PAUSED")
    terminal.press("m")
    terminal.expectText("sort: memory")
    terminal.press("Space")
    terminal.expectNoText("PAUSED")
    terminal.captureText("interactive.txt")
}
