function main(terminal) {
    terminal.expectText("Sort: CPU% descending")
    terminal.expectTextInRegion(2, 10, 74, 1, "terminal_engine")
    terminal.click(4, 8)
    terminal.expectText("Sort: PID ascending")
    terminal.expectTextInRegion(2, 10, 74, 1, "systemd")
    terminal.clickText("terminal_engine")
    terminal.expectText("Activated PID 1042")
    terminal.click(12, 3)
    terminal.typeText("qml")
    terminal.expectTextInRegion(2, 10, 74, 1, "qml_renderer")
    terminal.expectNoText("terminal_engine")
    terminal.clickText("qml_renderer")
    terminal.expectText("Activated PID 1089")
    terminal.captureText("filtered-activation.txt")
    terminal.press("Escape")
    terminal.expectText("terminal_engine")
    terminal.captureText("restored.txt")
}
