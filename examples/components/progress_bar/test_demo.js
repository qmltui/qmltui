/** @param {Terminal} terminal */
function main(terminal) {
    terminal.expectText("QmlTui.Controls ProgressBar Showcase");
    terminal.sleep(800);
    terminal.advanceTime(1000);
    terminal.sleep(800);
    terminal.advanceTime(1000);
    terminal.sleep(800);
    terminal.advanceTime(1000);
    terminal.sleep(800);
    terminal.advanceTime(1000);
    terminal.sleep(1500);
    terminal.stopRecording();
}
