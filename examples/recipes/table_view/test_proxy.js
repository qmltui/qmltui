function main(app) {
    app.expectText("Sort: CPU% descending")
    app.expectTextInRegion(2, 10, 74, 1, "terminal_engine")
    app.click(4, 8)
    app.expectText("Sort: PID ascending")
    app.expectTextInRegion(2, 10, 74, 1, "systemd")
    app.clickText("terminal_engine")
    app.expectText("Activated PID 1042")
    app.click(12, 3)
    app.typeText("qml")
    app.expectTextInRegion(2, 10, 74, 1, "qml_renderer")
    app.expectNoText("terminal_engine")
    app.clickText("qml_renderer")
    app.expectText("Activated PID 1089")
    app.captureText("filtered-activation.txt")
    app.press("Escape")
    app.expectText("terminal_engine")
    app.captureText("restored.txt")
    app.click(12, 3)
    app.press("Escape")
    app.press("s")
    app.expectText("Sort: PID descending")
}
